-- Apply once to a fresh PostgreSQL database as the PHP backend's table owner.
BEGIN;

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    email text NOT NULL UNIQUE CHECK (email = lower(email) AND btrim(email) <> ''),
    password_hash text NOT NULL,
    phone text NOT NULL DEFAULT '',
    address text NOT NULL DEFAULT '',
    role text NOT NULL CHECK (role IN ('ADMIN', 'CUSTOMER')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE clothing_categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    description text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE clothings (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES clothing_categories(id),
    name text NOT NULL CHECK (btrim(name) <> ''),
    type text NOT NULL CHECK (type IN ('DRESS','SUIT','COSTUME')),
    size text NOT NULL CHECK (btrim(size) <> ''),
    color text NOT NULL CHECK (btrim(color) <> ''),
    rental_price_per_day bigint NOT NULL CHECK (rental_price_per_day >= 0),
    stock integer NOT NULL CHECK (stock >= 0),
    condition text NOT NULL DEFAULT 'Baik',
    description text NOT NULL DEFAULT '',
    image_url text NOT NULL DEFAULT '',
    dress_style text,
    dry_cleaning_fee bigint CHECK (dry_cleaning_fee >= 0),
    theme text,
    accessory_fee bigint CHECK (accessory_fee >= 0),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK ((type = 'DRESS' AND dress_style IS NOT NULL AND dry_cleaning_fee IS NULL AND theme IS NULL AND accessory_fee IS NULL)
        OR (type = 'SUIT' AND dry_cleaning_fee IS NOT NULL AND dress_style IS NULL AND theme IS NULL AND accessory_fee IS NULL)
        OR (type = 'COSTUME' AND theme IS NOT NULL AND accessory_fee IS NOT NULL AND dress_style IS NULL AND dry_cleaning_fee IS NULL))
);
CREATE INDEX clothings_category_idx ON clothings(category_id);
CREATE INDEX clothings_catalog_idx ON clothings(type, rental_price_per_day) WHERE is_active;

CREATE TABLE rentals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES users(id),
    rental_date date NOT NULL,
    planned_return_date date NOT NULL CHECK (planned_return_date >= rental_date),
    actual_return_date date CHECK (actual_return_date >= rental_date),
    status text NOT NULL CHECK (status IN ('DRAFT','RENTED','RETURNED')),
    total_price bigint NOT NULL CHECK (total_price >= 0),
    return_fee bigint NOT NULL DEFAULT 0 CHECK (return_fee >= 0),
    request_key text NOT NULL,
    request_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(customer_id, request_key),
    CHECK ((status = 'RETURNED') = (actual_return_date IS NOT NULL))
);
CREATE INDEX rentals_due_idx ON rentals(planned_return_date) WHERE status = 'RENTED';

CREATE TABLE rental_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id integer NOT NULL REFERENCES rentals(id),
    clothing_id integer NOT NULL REFERENCES clothings(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    rental_days integer NOT NULL CHECK (rental_days > 0),
    price_per_day bigint NOT NULL CHECK (price_per_day >= 0),
    -- Snapshot for the entire line, exactly as in the Java/PHP demos.
    additional_fee bigint NOT NULL CHECK (additional_fee >= 0),
    subtotal bigint NOT NULL CHECK (subtotal = price_per_day * rental_days * quantity + additional_fee),
    UNIQUE(rental_id, clothing_id)
);
CREATE INDEX rental_items_clothing_idx ON rental_items(clothing_id);

CREATE TABLE payments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id integer NOT NULL REFERENCES rentals(id),
    payment_method text NOT NULL CHECK (payment_method IN ('CASH','TRANSFER','EWALLET')),
    amount bigint NOT NULL CHECK (amount > 0),
    payment_status text NOT NULL CHECK (payment_status = 'PAID'),
    cash_received bigint,
    change_amount bigint,
    bank_name text,
    provider text,
    request_key text NOT NULL,
    request_hash text NOT NULL,
    payment_date timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(rental_id, request_key),
    CHECK ((payment_method = 'CASH' AND cash_received IS NOT NULL AND cash_received >= amount
            AND change_amount IS NOT NULL AND change_amount = cash_received - amount AND bank_name IS NULL AND provider IS NULL)
        OR (payment_method = 'TRANSFER' AND bank_name IS NOT NULL AND btrim(bank_name) <> ''
            AND provider IS NULL AND cash_received IS NULL AND change_amount IS NULL)
        OR (payment_method = 'EWALLET' AND provider IS NOT NULL AND btrim(provider) <> ''
            AND bank_name IS NULL AND cash_received IS NULL AND change_amount IS NULL))
);

CREATE TABLE invoices (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id integer NOT NULL UNIQUE REFERENCES rentals(id),
    invoice_number text NOT NULL UNIQUE,
    issue_date timestamptz NOT NULL DEFAULT now(),
    total_amount bigint NOT NULL CHECK (total_amount >= 0)
);

CREATE TABLE rental_returns (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id integer NOT NULL UNIQUE REFERENCES rentals(id),
    processed_by integer NOT NULL REFERENCES users(id),
    return_date date NOT NULL,
    condition_on_return text NOT NULL CHECK (btrim(condition_on_return) <> ''),
    total_fee bigint NOT NULL CHECK (total_fee >= 0),
    notes text NOT NULL CHECK (btrim(notes) <> '')
);

CREATE TABLE inventory_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clothing_id integer NOT NULL REFERENCES clothings(id),
    admin_id integer REFERENCES users(id),
    actor_id integer REFERENCES users(id),
    change_type text NOT NULL CHECK (change_type IN ('INITIAL','ADJUSTMENT','RENTAL','RETURN')),
    quantity_changed integer NOT NULL,
    notes text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX inventory_logs_clothing_idx ON inventory_logs(clothing_id);
CREATE INDEX inventory_logs_time_idx ON inventory_logs(created_at DESC);

-- RLS with no public policies denies direct Data API clients. PHP connects
-- as the table owner over PDO. These statements also work on local PostgreSQL.
DO $security$
DECLARE
    table_name text;
    client_role text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['users','clothing_categories','clothings','rentals','rental_items','payments','invoices','rental_returns','inventory_logs'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', table_name);
        EXECUTE format('REVOKE ALL ON TABLE %I FROM PUBLIC', table_name);
        FOREACH client_role IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
            IF EXISTS (SELECT FROM pg_roles WHERE rolname = client_role) THEN
                EXECUTE format('REVOKE ALL ON TABLE %I FROM %I', table_name, client_role);
                EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I', pg_get_serial_sequence(table_name,'id'), client_role);
            END IF;
        END LOOP;
    END LOOP;
END
$security$;
COMMIT;
